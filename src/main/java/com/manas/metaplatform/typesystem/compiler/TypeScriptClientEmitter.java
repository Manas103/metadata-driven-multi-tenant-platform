package com.manas.metaplatform.typesystem.compiler;

import com.manas.metaplatform.typesystem.dsl.FieldDecl;
import com.manas.metaplatform.typesystem.dsl.TypeDecl;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Emits a typed TypeScript interface and a typed TypeScript client class for one
 * {@link TypeDecl}, plus (via {@link #emitIndex}) the combined registry file the
 * differential query runner uses to drive all 40 generated clients uniformly. Mirrors
 * {@link JavaClientEmitter} field for field, so the two languages agree on what "the same
 * request" means; that agreement is exactly what the 2,000-query differential run checks.
 */
public final class TypeScriptClientEmitter {

    public Map<String, String> emit(TypeDecl type) {
        Map<String, String> files = new LinkedHashMap<>();
        files.put("model/" + type.name() + ".ts", emitModel(type));
        files.put("client/" + type.name() + "Client.ts", emitClient(type));
        return files;
    }

    private String emitModel(TypeDecl type) {
        StringBuilder sb = new StringBuilder();
        sb.append("// GENERATED by com.manas.metaplatform.typesystem.compiler.TypeScriptClientEmitter\n");
        sb.append("// from the single declaration of type ").append(type.name())
                .append(" in src/main/resources/typesystem/declared-types.dsl. Do not edit by hand.\n\n");
        sb.append("export interface ").append(type.name()).append(" {\n");
        sb.append("  id: number;\n");
        for (FieldDecl field : type.fields()) {
            sb.append("  ").append(field.name()).append(": ").append(tsType(field)).append(";\n");
        }
        sb.append("}\n\n");
        sb.append("export type New").append(type.name()).append(" = Omit<").append(type.name())
                .append(", \"id\">;\n");
        return sb.toString();
    }

    private String emitClient(TypeDecl type) {
        String name = type.name();
        StringBuilder sb = new StringBuilder();
        sb.append("// GENERATED by com.manas.metaplatform.typesystem.compiler.TypeScriptClientEmitter\n");
        sb.append("// from the single declaration of type ").append(name)
                .append(" in src/main/resources/typesystem/declared-types.dsl. Do not edit by hand.\n\n");
        sb.append("import type { ").append(name).append(", New").append(name).append(" } from \"../model/")
                .append(name).append(".ts\";\n");
        sb.append("import { httpPost, httpGet, httpGetArray, buildFilterQueryString } from \"../runtime/httpSupport.ts\";\n\n");
        sb.append("export class ").append(name).append("Client {\n");
        sb.append("  private baseUrl: string;\n\n");
        sb.append("  constructor(baseUrl: string) {\n    this.baseUrl = baseUrl;\n  }\n\n");
        sb.append("  typeName(): string {\n    return \"").append(name).append("\";\n  }\n\n");
        sb.append("  async createTyped(body: New").append(name).append("): Promise<").append(name).append("> {\n");
        sb.append("    return httpPost<").append(name).append(">(this.baseUrl + \"/api/types/")
                .append(name).append("\", body);\n  }\n\n");
        sb.append("  async getTyped(id: number): Promise<").append(name).append("> {\n");
        sb.append("    return httpGet<").append(name).append(">(this.baseUrl + \"/api/types/")
                .append(name).append("/\" + id);\n  }\n\n");
        sb.append("  async listTyped(filters: Record<string, unknown>): Promise<").append(name)
                .append("[]> {\n");
        sb.append("    return httpGetArray<").append(name).append(">(this.baseUrl + \"/api/types/")
                .append(name).append("\" + buildFilterQueryString(filters));\n  }\n\n");
        sb.append("  async create(fields: Record<string, unknown>): Promise<Record<string, unknown>> {\n");
        sb.append("    return this.createTyped(fields as New").append(name).append(");\n  }\n\n");
        sb.append("  async getById(id: number): Promise<Record<string, unknown>> {\n");
        sb.append("    return this.getTyped(id);\n  }\n\n");
        sb.append("  async list(equalityFilters: Record<string, unknown>): Promise<Record<string, unknown>[]> {\n");
        sb.append("    return this.listTyped(equalityFilters);\n  }\n");
        sb.append("}\n");
        return sb.toString();
    }

    /** The combined registry (also generated, but from all 40 declarations at once rather
     * than one) the hand-written {@code run-queries.ts} driver imports to look up "the client
     * for type X" without hard-coding all 40 names itself. */
    public String emitIndex(List<TypeDecl> types) {
        StringBuilder sb = new StringBuilder();
        sb.append("// GENERATED by com.manas.metaplatform.typesystem.compiler.TypeScriptClientEmitter\n");
        sb.append("// Registry of all ").append(types.size())
                .append(" declared types' generated clients. Do not edit by hand.\n\n");
        for (TypeDecl type : types) {
            sb.append("import { ").append(type.name()).append("Client } from \"./client/")
                    .append(type.name()).append("Client.ts\";\n");
        }
        sb.append("\nexport interface GenericClientOps {\n");
        sb.append("  typeName(): string;\n");
        sb.append("  create(fields: Record<string, unknown>): Promise<Record<string, unknown>>;\n");
        sb.append("  getById(id: number): Promise<Record<string, unknown>>;\n");
        sb.append("  list(equalityFilters: Record<string, unknown>): Promise<Record<string, unknown>[]>;\n");
        sb.append("}\n\n");
        sb.append("export function buildClients(baseUrl: string): Record<string, GenericClientOps> {\n");
        sb.append("  return {\n");
        for (int i = 0; i < types.size(); i++) {
            String name = types.get(i).name();
            sb.append("    ").append(name).append(": new ").append(name).append("Client(baseUrl)")
                    .append(i < types.size() - 1 ? "," : "").append("\n");
        }
        sb.append("  };\n}\n");
        return sb.toString();
    }

    private String tsType(FieldDecl field) {
        return switch (field.type()) {
            case STRING -> "string";
            case NUMBER -> "number";
            case BOOLEAN -> "boolean";
        };
    }
}
