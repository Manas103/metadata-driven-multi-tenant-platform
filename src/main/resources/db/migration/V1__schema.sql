-- Schema for the JPA entities, as Hibernate 6 generates it for PostgreSQL
-- (jakarta.persistence.schema-generation against PostgreSQL 16), plus the foreign keys
-- and indexes Hibernate does not emit. The production profile runs Flyway, then
-- ddl-auto=validate checks the entities against this. The declared-type tables of the
-- type platform are not here: TypeSystemBootstrap creates them from the type DSL.


create table app_users (
    id bigint generated by default as identity,
    role_id bigint not null,
    tenant_id bigint not null,
    name varchar(200) not null,
    primary key (id)
);

create table field_definitions (
    id bigint generated by default as identity,
    object_definition_id bigint not null,
    field_type varchar(20) not null check (field_type in ('STRING','NUMBER','BOOLEAN')),
    name varchar(200) not null,
    primary key (id),
    unique (object_definition_id, name)
);

create table field_values (
    boolean_value boolean,
    number_value numeric(20,6),
    field_definition_id bigint not null,
    id bigint generated by default as identity,
    record_id bigint not null,
    string_value varchar(4000),
    primary key (id)
);

create table fund_accounts (
    id bigint generated by default as identity,
    tenant_id bigint not null,
    account_name varchar(200) not null,
    primary key (id)
);

create table ledger_entries (
    cost_basis numeric(20,6) not null,
    effective_date date not null,
    quantity numeric(20,6) not null,
    realized_pnl numeric(20,6) not null,
    version integer not null,
    account_id bigint not null,
    as_of_from timestamp(6) with time zone not null,
    as_of_to timestamp(6) with time zone,
    id bigint generated by default as identity,
    symbol varchar(16) not null,
    entry_type varchar(20) not null check (entry_type in ('TRADE','CORPORATE_ACTION')),
    fact_id varchar(64) not null,
    primary key (id)
);

create table object_definitions (
    id bigint generated by default as identity,
    tenant_id bigint not null,
    name varchar(200) not null,
    primary key (id),
    unique (tenant_id, name)
);

create table record_shares (
    id bigint generated by default as identity,
    record_id bigint not null,
    shared_with_user_id bigint not null,
    primary key (id)
);

create table records (
    id bigint generated by default as identity,
    object_definition_id bigint not null,
    owner_user_id bigint,
    tenant_id bigint not null,
    primary key (id)
);

create table roles (
    id bigint generated by default as identity,
    parent_role_id bigint,
    tenant_id bigint not null,
    name varchar(100) not null,
    primary key (id)
);

create table tenants (
    id bigint generated by default as identity,
    name varchar(200) not null,
    primary key (id),
    unique (name)
);

-- referential integrity
alter table object_definitions add constraint fk_objdef_tenant foreign key (tenant_id) references tenants (id);
alter table field_definitions add constraint fk_fielddef_objdef foreign key (object_definition_id) references object_definitions (id);
alter table roles add constraint fk_role_tenant foreign key (tenant_id) references tenants (id);
alter table roles add constraint fk_role_parent foreign key (parent_role_id) references roles (id);
alter table app_users add constraint fk_user_tenant foreign key (tenant_id) references tenants (id);
alter table app_users add constraint fk_user_role foreign key (role_id) references roles (id);
alter table records add constraint fk_record_tenant foreign key (tenant_id) references tenants (id);
alter table records add constraint fk_record_objdef foreign key (object_definition_id) references object_definitions (id);
alter table records add constraint fk_record_owner foreign key (owner_user_id) references app_users (id);
alter table field_values add constraint fk_value_record foreign key (record_id) references records (id);
alter table field_values add constraint fk_value_fielddef foreign key (field_definition_id) references field_definitions (id);
alter table field_values add constraint uq_value_record_field unique (record_id, field_definition_id);
alter table record_shares add constraint fk_share_record foreign key (record_id) references records (id);
alter table record_shares add constraint fk_share_user foreign key (shared_with_user_id) references app_users (id);
alter table fund_accounts add constraint fk_fund_tenant foreign key (tenant_id) references tenants (id);
alter table ledger_entries add constraint fk_ledger_account foreign key (account_id) references fund_accounts (id);
alter table ledger_entries add constraint uq_ledger_fact_version unique (fact_id, version);

-- the access paths the compiled SQL and the ledger use
create index ix_records_tenant_object on records (tenant_id, object_definition_id);
create index ix_records_owner on records (owner_user_id);
create index ix_values_field on field_values (field_definition_id);
create index ix_shares_user on record_shares (shared_with_user_id, record_id);
create index ix_users_tenant on app_users (tenant_id);
create index ix_ledger_account on ledger_entries (account_id, fact_id);
create index ix_ledger_open on ledger_entries (effective_date) where as_of_to is null;
